ALTER TABLE carts ADD CONSTRAINT ck_carts_version CHECK (version >= 0);

CREATE TABLE order_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES members(id),
    request_key varchar(80) NOT NULL,
    request_hash varchar(64) NOT NULL,
    order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT uk_order_requests_member_key UNIQUE (member_id, request_key),
    CONSTRAINT ck_order_requests_key CHECK (request_key ~ '^[A-Za-z0-9_-]{16,80}$'),
    CONSTRAINT ck_order_requests_hash CHECK (request_hash ~ '^[0-9a-f]{64}$')
);
