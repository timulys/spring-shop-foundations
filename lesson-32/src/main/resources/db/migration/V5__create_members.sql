CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(30) NOT NULL,
    display_name VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    CONSTRAINT uk_members_login_id UNIQUE (login_id),
    CONSTRAINT ck_members_login_id CHECK (login_id ~ '^[a-z][a-z0-9_]{2,29}$'),
    CONSTRAINT ck_members_display_name CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 50),
    CONSTRAINT ck_members_password_hash CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);
