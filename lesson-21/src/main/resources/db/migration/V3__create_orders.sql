CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status varchar(20) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
    payment_mode varchar(20) NOT NULL CHECK (payment_mode = 'SIMULATED'),
    subtotal_won bigint NOT NULL CHECK (subtotal_won >= 0),
    discount_won bigint NOT NULL CHECK (discount_won >= 0 AND discount_won <= subtotal_won),
    shipping_fee_won bigint NOT NULL CHECK (shipping_fee_won >= 0),
    total_won bigint NOT NULL CHECK (total_won = subtotal_won - discount_won + shipping_fee_won),
    created_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id),
    product_code varchar(20) NOT NULL,
    product_name varchar(100) NOT NULL,
    unit_price_won bigint NOT NULL CHECK (unit_price_won BETWEEN 1 AND 1000000),
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT order_items_order_product_unique UNIQUE (order_id, product_code)
);
